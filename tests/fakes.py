def wechat_notify_plaintext(
    *,
    out_trade_no: str,
    transaction_id: str,
    amount_fen: int,
    trade_state: str = "SUCCESS",
    success_time: datetime | None = None,
    currency: str = "CNY",
) -> dict:
    """The decrypted ``transaction`` object WeChat puts inside ``resource``."""
    moment = success_time or datetime.now(UTC)
    return {
        "mchid": "1900000001",
        "appid": "wxtest000000000001",
        "out_trade_no": out_trade_no,
        "transaction_id": transaction_id,
        "trade_type": "NATIVE",
        "trade_state": trade_state,
        "trade_state_desc": "支付成功" if trade_state == "SUCCESS" else trade_state,
        "bank_type": "OTHERS",
        "success_time": moment.strftime("%Y-%m-%dT%H:%M:%S+08:00"),
        "payer": {"openid": "oUpF8uMuAJO_M2pxb1Q9zNjWeS6o"},
        "amount": {
            "total": amount_fen,
            "payer_total": amount_fen,
            "currency": currency,
            "payer_currency": currency,
        },
    }


def make_wechat_notify(
    *,
    keys: WechatTestKeys,
    out_trade_no: str,
    amount_fen: int,
    transaction_id: str | None = None,
    trade_state: str = "SUCCESS",
    success_time: datetime | None = None,
    event_type: str = "TRANSACTION.SUCCESS",
    timestamp: int | None = None,
    nonce: str | None = None,
    tamper_body: bool = False,
    tamper_signature: bool = False,
    bad_serial: bool = False,
    omit_signature: bool = False,
) -> tuple[dict[str, str], bytes]:
    """Build a genuinely signed, genuinely encrypted WeChat Pay notification.

    Returns ``(headers, raw_body)`` ready to hand to
    ``WechatPayGateway.parse_notification`` (or to ``TestClient.post``).

    The tampering switches exist so a test can prove the adapter *fails closed*
    rather than merely asserting that the happy path works.
    """
    transaction_id = transaction_id or f"4200001{uuid.uuid4().hex[:14]}"
    timestamp = timestamp if timestamp is not None else int(datetime.now(UTC).timestamp())
    nonce = nonce or secrets.token_hex(8)

    plaintext = json.dumps(
        wechat_notify_plaintext(
            out_trade_no=out_trade_no,
            transaction_id=transaction_id,
            amount_fen=amount_fen,
            trade_state=trade_state,
            success_time=success_time,
        )
    ).encode("utf-8")

    associated_data = "transaction"
    aesgcm = AESGCM(keys.api_v3_key.encode("utf-8"))
    ciphertext = aesgcm.encrypt(
        nonce.encode("utf-8"), plaintext, associated_data.encode("utf-8")
    )

    envelope = {
        "id": str(uuid.uuid4()),
        "create_time": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%S+08:00"),
        "resource_type": "encrypt-resource",
        "event_type": event_type,
        "summary": "支付成功",
        "resource": {
            "original_type": "transaction",
            "algorithm": "AEAD_AES_256_GCM",
            "ciphertext": base64.b64encode(ciphertext).decode("ascii"),
            "associated_data": associated_data,
            "nonce": nonce,
        },
    }
    raw_body = json.dumps(envelope, ensure_ascii=False).encode("utf-8")

    signature = _sign_notification(
        private_key_pem=keys.private_key_pem,
        timestamp=timestamp,
        nonce=nonce,
        body=raw_body,
    )

    if tamper_body:
        # Flip a byte in the ciphertext but keep the signature over the original
        # body — exactly what an attacker in the middle would produce.
        mutated = json.loads(raw_body.decode("utf-8"))
        original = mutated["resource"]["ciphertext"]
        mutated["resource"]["ciphertext"] = base64.b64encode(
            bytes([base64.b64decode(original)[0] ^ 0xFF]) + base64.b64decode(original)[1:]
        ).decode("ascii")
        raw_body = json.dumps(mutated, ensure_ascii=False).encode("utf-8")

    if tamper_signature:
        signature = base64.b64encode(b"not-a-real-signature" * 4).decode("ascii")

    headers = {
        "Wechatpay-Timestamp": str(timestamp),
        "Wechatpay-Nonce": nonce,
        "Wechatpay-Serial": "UNKNOWN_SERIAL_0000" if bad_serial else keys.public_key_id,
    }
    if not omit_signature:
        headers["Wechatpay-Signature"] = signature

    return headers, raw_body


def _sign_notification(
    *, private_key_pem: str, timestamp: int, nonce: str, body: bytes
) -> str:
    """RSA-SHA256 over ``f"{timestamp}\\n{nonce}\\n{body}\\n"``, base64 encoded."""
    from cryptography.hazmat.primitives.serialization import load_pem_private_key

    key = load_pem_private_key(private_key_pem.encode("utf-8"), password=None)
    message = f"{timestamp}\n{nonce}\n{body.decode('utf-8')}\n".encode("utf-8")
    signature = key.sign(message, padding.PKCS1v15(), hashes.SHA256())
    return base64.b64encode(signature).decode("ascii")
