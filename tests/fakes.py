@dataclass
class FakePaymentGateway:
    """HMAC-signed stand-in for WeChat Pay.

    ``parse_notification`` verifies ``X-Fake-Signature`` =
    ``hex(hmac_sha256(secret_key, body))`` before returning anything, so it fails
    closed in the same *shape* as the real adapter.  Use
    :meth:`build_notify` to construct a valid callback.
    """

    secret_key: str = "dev-only-change-me"
    charges: list[ChargeRequest] = field(default_factory=list)
    closed: list[str] = field(default_factory=list)
    orders: dict[str, PaymentNotification] = field(default_factory=dict)
    fail_create: bool = False

    def create_charge(self, req: ChargeRequest) -> ChargeResult:
        if self.fail_create:
            raise RuntimeError("fake payment gateway configured to fail")
        self.charges.append(req)
        return ChargeResult(
            code_url=f"weixin://wxpay/bizpayurl?pr=FAKE{req.out_trade_no}",
            provider_order_id=f"fake-{req.out_trade_no}",
        )

    def parse_notification(
        self, headers: dict[str, str], body: bytes
    ) -> PaymentNotification:
        lowered = {k.lower(): v for k, v in headers.items()}
        signature = lowered.get("x-fake-signature", "")
        expected = hmac.new(
            self.secret_key.encode("utf-8"), body, hashlib.sha256
        ).hexdigest()
        if not hmac.compare_digest(signature, expected):
            raise PaymentSignatureError("bad fake signature")

        payload = json.loads(body.decode("utf-8"))
        notification = PaymentNotification(
            out_trade_no=payload["out_trade_no"],
            transaction_id=payload["transaction_id"],
            amount_fen=payload["amount_fen"],
            trade_state=payload.get("trade_state", "SUCCESS"),
            success_time=payload.get("success_time"),
        )
        self.orders[notification.out_trade_no] = notification
        return notification

    def query_order(self, out_trade_no: str) -> PaymentNotification | None:
        return self.orders.get(out_trade_no)

    def close_order(self, out_trade_no: str) -> None:
        self.closed.append(out_trade_no)

    def build_notify(
        self,
        *,
        out_trade_no: str,
        amount_fen: int,
        transaction_id: str | None = None,
        trade_state: str = "SUCCESS",
        success_time: datetime | None = None,
    ) -> tuple[dict[str, str], bytes]:
        """A valid, correctly signed callback for this gateway."""
        body = json.dumps(
            {
                "out_trade_no": out_trade_no,
                "transaction_id": transaction_id or f"FAKE{uuid.uuid4().hex[:16]}",
                "amount_fen": amount_fen,
                "trade_state": trade_state,
                "success_time": (
                    success_time or datetime.now(UTC)
                ).isoformat(),
            }
        ).encode("utf-8")
        signature = hmac.new(
            self.secret_key.encode("utf-8"), body, hashlib.sha256
        ).hexdigest()
        return {"X-Fake-Signature": signature}, body


