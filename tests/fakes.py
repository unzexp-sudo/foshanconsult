@dataclass
class FakeCalendarGateway:
    """In-memory calendar.

    ``busy`` holds the pre-existing commitments.  A hold created through
    :meth:`create_hold` also becomes busy, which is what makes the
    "a slot already held is not offered" test meaningful.
    """

    busy: list[BusyInterval] = field(default_factory=list)
    events: dict[str, dict] = field(default_factory=dict)
    released: list[str] = field(default_factory=list)
    confirmed: list[str] = field(default_factory=list)
    _counter: int = 0

    def freebusy(self, time_min: datetime, time_max: datetime) -> list[BusyInterval]:
        return [
            interval
            for interval in self.busy
            if interval.start < time_max and interval.end > time_min
        ]

    def create_hold(
        self,
        *,
        summary: str,
        description: str,
        start: datetime,
        end: datetime,
        reference: str,
    ) -> CalendarEvent:
        self._counter += 1
        event_id = f"evt-{self._counter:04d}"
        self.events[event_id] = {
            "summary": summary,
            "description": description,
            "start": start,
            "end": end,
            "reference": reference,
            "status": "tentative",
        }
        self.busy.append(BusyInterval(start=start, end=end))
        return CalendarEvent(event_id=event_id, html_link=f"https://cal.example/{event_id}")

    def confirm(self, event_id: str, *, summary: str, description: str) -> None:
        if event_id not in self.events:
            raise KeyError(f"unknown event {event_id}")
        self.events[event_id].update(
            summary=summary, description=description, status="confirmed"
        )
        self.confirmed.append(event_id)

    def release(self, event_id: str) -> None:
        # Idempotent on purpose: releasing an unknown event is not an error.
        event = self.events.pop(event_id, None)
        self.released.append(event_id)
        if event is not None:
            self.busy = [
                interval
                for interval in self.busy
                if not (interval.start == event["start"] and interval.end == event["end"])
            ]

    # convenience for tests
    def add_busy(self, start: datetime, end: datetime) -> None:
        self.busy.append(BusyInterval(start=start, end=end))


