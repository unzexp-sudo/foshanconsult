WECHAT_API_V3_KEY = "0123456789abcdef0123456789abcdef"  # exactly 32 chars


@dataclass(frozen=True)
class WechatTestKeys:
    api_v3_key: str
    serial_no: str  # merchant apiclient_cert serial number
    public_key_id: str  # Wechatpay-Serial value on inbound notifications
    private_key_pem: str  # platform private key — signs notifications
    private_key_path: Path  # merchant apiclient_key.pem
    public_key_path: Path  # 微信支付公钥 — inbound verification


def make_wechat_keys(tmp_path: Path) -> WechatTestKeys:
    """Two throwaway RSA keypairs: one merchant, one "platform"."""
    tmp_path.mkdir(parents=True, exist_ok=True)

    merchant_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    merchant_pem = merchant_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    private_key_path = tmp_path / "apiclient_key.pem"
    private_key_path.write_bytes(merchant_pem)

    platform_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    platform_pem = platform_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    public_key_path = tmp_path / "pub_key.pem"
    public_key_path.write_bytes(
        platform_key.public_key().public_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PublicFormat.SubjectPublicKeyInfo,
        )
    )

    return WechatTestKeys(
        api_v3_key=WECHAT_API_V3_KEY,
        serial_no="4D2B4A1E5C6F7A8B9C0D1E2F3A4B5C6D7E8F9A0B",
        public_key_id="PUB_KEY_ID_TEST_0001",
        private_key_pem=platform_pem.decode("utf-8"),
        private_key_path=private_key_path,
        public_key_path=public_key_path,
    )


